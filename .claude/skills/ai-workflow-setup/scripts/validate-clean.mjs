#!/usr/bin/env node
// validate-clean.mjs (ai-workflow-setup): run the CI gates in a clean temporary checkout, the way
// ai-gates will on GitHub, so files that only exist locally (gitignored, untracked, stale build
// info, CRLF endings) cannot make local green look like CI green. Removes the checkout afterwards.
//   node validate-clean.mjs [--ref <commit-ish, default HEAD>] [--in-repo] [--keep] [--json]
//   --in-repo  put the checkout under .claude/worktrees/ like a subagent's worktree (doctor); the default,
//              a system temp dir, is closer to CI because nothing above it has a node_modules.
// Steps: git -c core.autocrlf=false worktree add --detach <tmp> <ref>; worktree setup (install +
// codegen) from .claude/ai-workflow.json; verify; trace --check; rules-check; then reports any
// tracked file the steps modified, with what to propose for it. Turborepo and Nx caches are bypassed.
import { readFileSync, mkdtempSync, existsSync, rmSync, mkdirSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { join } from 'node:path';
import { tmpdir } from 'node:os';

const argv = process.argv.slice(2);
const val = (f) => { const i = argv.indexOf(f); return i >= 0 ? argv[i + 1] : null; };
const ref = val('--ref') || 'HEAD';
// Turborepo 2.x shares its local cache with git worktrees, so a task output cached in the developer's checkout
// could be replayed here and hide what a fresh CI machine hits. Force task runners to rerun everything.
const NO_TASK_CACHE = { TURBO_FORCE: 'true', NX_SKIP_NX_CACHE: 'true' };
const sh = (cmd, cwd, timeout = 20 * 60 * 1000) => {
  const t0 = Date.now();
  const r = spawnSync(cmd, { cwd, shell: true, encoding: 'utf8', timeout, env: { ...process.env, CI: 'true', FORCE_COLOR: '0', ...NO_TASK_CACHE }, maxBuffer: 64 * 1024 * 1024 });
  return { ok: r.status === 0, status: r.status, secs: Math.round((Date.now() - t0) / 1000), out: `${r.stdout || ''}${r.stderr || ''}` };
};
const git = (args, cwd) => spawnSync('git', args, { cwd, encoding: 'utf8' });
// What to propose for a committed file the steps rewrote (the user decides; nothing is changed here).
const HINTS = [
  [/\.tsbuildinfo$/, 'TypeScript build info: stop tracking it (git rm --cached, *.tsbuildinfo in .gitignore); a stale copy makes tsc skip emitting'],
  [/(^|\/)next-env\.d\.ts$/, 'Next.js rewrites it on build: commit the version this Next.js writes, or stop tracking it as create-next-app does (type-check must then run after build)'],
  [/(^|\/)(dist|build|out|\.next|\.turbo|coverage)\//, 'build output: stop tracking it (git rm -r --cached, a .gitignore line)'],
];
const HINT_OTHER = 'generated by a step: commit the regenerated version, or stop tracking it';
// Failure output: error lines first (parallel task runners print the cause long before the summary), then the tail.
const ANSI = new RegExp(`${String.fromCharCode(27)}\\[[0-9;]*m`, 'g');
const brief = (out) => {
  const ls = out.replace(ANSI, '').split('\n');
  const errs = [...new Set(ls.filter((l) => /\berror\b|ERR!|\bFAIL\b|\u2715|Cannot find/i.test(l)))].slice(0, 15);
  const tail = ls.slice(-25).filter((l) => !errs.includes(l));
  return [...errs, ...(errs.length && tail.length ? ['...'] : []), ...tail].join('\n');
};

const top = git(['rev-parse', '--show-toplevel'], process.cwd());
if (top.status !== 0) { console.error('validate-clean: not a git repository'); process.exit(2); }
const ROOT = top.stdout.trim();
const sha = git(['rev-parse', '--short', ref], ROOT).stdout.trim();
const parent = argv.includes('--in-repo') ? join(ROOT, '.claude', 'worktrees') : tmpdir();
mkdirSync(parent, { recursive: true });
const dir = mkdtempSync(join(parent, 'aiwf-clean-'));
rmSync(dir, { recursive: true, force: true });
const add = git(['-c', 'core.autocrlf=false', '-c', 'core.eol=lf', 'worktree', 'add', '--detach', dir, ref], ROOT);
if (add.status !== 0) { console.error(`validate-clean: worktree add failed: ${add.stderr}`); process.exit(2); }

const results = [];
let cfg = {};
try {
  try { cfg = JSON.parse(readFileSync(join(dir, '.claude', 'ai-workflow.json'), 'utf8')); }
  catch { results.push({ step: 'config', ok: false, out: '.claude/ai-workflow.json is not committed at this ref' }); }
  const c = cfg.commands || {};
  const steps = [
    ['worktree setup', c.worktreeSetup || c.install],
    ['verify (G3)', c.verify],
    ['trace check (G4)', existsSync(join(dir, 'scripts', 'trace.mjs')) ? 'node scripts/trace.mjs --check --quiet' : null],
    ['rules check', existsSync(join(dir, 'scripts', 'rules-check.mjs')) ? 'node scripts/rules-check.mjs' : null],
  ];
  for (const [step, cmd] of steps) {
    if (!cmd) { results.push({ step, ok: false, skipped: true, out: 'no command configured' }); continue; }
    const r = sh(cmd, dir);
    results.push({ step, cmd, ok: r.ok, secs: r.secs, out: r.ok ? '' : brief(r.out) });
    if (!r.ok && step === 'worktree setup') break;
  }
  const modified = git(['status', '--porcelain', '--untracked-files=no'], dir).stdout.split('\n').filter(Boolean);
  if (modified.length) {
    const lines = modified.slice(0, 20).map((l) => { const h = HINTS.find(([re]) => re.test(l.slice(3))); return `${l}  <- ${h ? h[1] : HINT_OTHER}`; });
    results.push({ step: 'tracked files untouched', ok: false, out: `the steps changed committed files; in agent worktrees that is an unexpected diff (scope-check flags it, worktree cleanup stops):\n${lines.join('\n')}` });
  } else results.push({ step: 'tracked files untouched', ok: true });
} finally {
  if (!argv.includes('--keep')) {
    git(['worktree', 'remove', '--force', dir], ROOT);
    git(['worktree', 'prune'], ROOT);
    rmSync(dir, { recursive: true, force: true });
  }
}

const ok = results.every((r) => r.ok);
if (argv.includes('--json')) console.log(JSON.stringify({ ref, sha, dir, ok, results }, null, 2));
else {
  console.log(`clean checkout of ${ref} (${sha})${argv.includes('--keep') ? ` kept at ${dir}` : ', removed afterwards'}`);
  for (const r of results) {
    console.log(`${r.ok ? 'PASS' : r.skipped ? 'SKIP' : 'FAIL'}  ${r.step}${r.cmd ? `: ${r.cmd}` : ''}${r.secs != null ? ` (${r.secs}s)` : ''}`);
    if (!r.ok && r.out) console.log(r.out.replace(/^/gm, '      '));
  }
  console.log(ok ? 'All gates green in a clean checkout. This is local: ai-gates on GitHub has not run until the branch is pushed.'
    : 'Not green in a clean checkout: fix before calling the scaffold done.');
}
process.exit(ok ? 0 : 1);
